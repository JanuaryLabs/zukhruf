export const testingTs = `import { readFile, readdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';

import pg from 'pg';

// src/ (development) and dist/ (default) each sit one level below the package
// root that holds migrations/.
const migrationsDir = resolve(import.meta.dirname, '..', 'migrations');

/**
 * Builds the schema of the committed migrations in an empty database: it runs
 * each migrations/<name>/migration.sql in order. It keeps no
 * _prisma_migrations record, because a test database is thrown away and never
 * migrated again. The deploy target applies migrations everywhere else.
 */
export async function applySchema(connectionString: string): Promise<void> {
  const migrations = (await readdir(migrationsDir, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted();
  const client = new pg.Client({ connectionString });
  await client.connect();
  try {
    for (const migration of migrations) {
      await client.query(
        await readFile(join(migrationsDir, migration, 'migration.sql'), 'utf8'),
      );
    }
  } finally {
    await client.end();
  }
}
`;

/** The test of the db package, or of a backend that imports it. */
export function databaseTestTs(imports: {
  client: string;
  testing: string;
}): string {
  return `import assert from 'node:assert/strict';
import { test } from 'node:test';

import { Postgres } from '@zukhruf/testing/postgres';

import { createPrisma } from '${imports.client}';
import { applySchema } from '${imports.testing}';

const postgres = new Postgres({ environment: process.env });

test('the client answers a query on a database with the schema of the migrations', async () => {
  await using database = await postgres.database();
  await applySchema(database.connectionString);
  const prisma = createPrisma({ connectionString: database.connectionString });
  try {
    assert.deepEqual(await prisma.$queryRaw\`SELECT 1 AS one\`, [{ one: 1 }]);
  } finally {
    await prisma.$disconnect();
  }
});
`;
}

