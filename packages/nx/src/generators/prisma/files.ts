/** The local Postgres of compose.dev.yml: what the db package and a wired backend connect to in development. */
export interface LocalDatabase {
  /** The host port, on 127.0.0.1. */
  port: number;
  /** The database, named after the workspace scope. */
  name: string;
}

export function localConnectionString(database: LocalDatabase): string {
  return `postgresql://postgres:postgres@127.0.0.1:${database.port}/${database.name}`;
}

export function envExample(database: LocalDatabase): string {
  return `# Copy to \`.env\` (gitignored). Nx loads it into each task of this project, so
# \`nx run <project>:migrate\` and \`deploy\` need no dotenv. The URL is the local
# Postgres of compose.dev.yml, which the up target starts.
# Every setup runs under production; no code reads NODE_ENV (ADR 0016).
NODE_ENV=production
CONNECTION_STRING=${localConnectionString(database)}
# Optional: the shadow database of \`prisma migrate dev\`.
SHADOW_CONNECTION_STRING=
`;
}

export function composeDevYml(
  database: LocalDatabase,
  packageName: string,
): string {
  return `# The local Postgres of development, which @zukhruf/nx:prisma writes. \`nx run
# ${packageName}:up\` starts it and applies the migrations, and the serve
# target of a wired backend runs up first. It listens on 127.0.0.1 only; the
# deployed stack runs its own Postgres, of the same image.
services:
  database:
    image: ${postgresImage}
    ports:
      - '127.0.0.1:${database.port}:5432'
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: ${database.name}
    # Postgres 18 keeps its data in a folder of its major version under
    # /var/lib/postgresql, so the volume holds the parent folder.
    volumes:
      - database:/var/lib/postgresql
    # up waits for this check before it applies the migrations.
    healthcheck:
      test: ['CMD', 'pg_isready', '-U', 'postgres', '-d', '${database.name}']
      interval: 2s
      timeout: 5s
      retries: 15
    restart: unless-stopped

volumes:
  database:
`;
}

export interface MigrationDockerfileOptions {
  projectRoot: string;
  packageName: string;
}

export function migrationDockerfile(
  options: MigrationDockerfileOptions,
): string {
  const { projectRoot, packageName } = options;
  return `# syntax=docker/dockerfile:1.7-labs
# @zukhruf/nx:prisma writes this file. Build from the workspace root:
# \`docker build --file ${projectRoot}/Dockerfile.migration .\`. The container
# gets CONNECTION_STRING from its environment and applies the migrations.

FROM node:lts-alpine
# The lockfile is the latest npm's; the image's bundled npm can be older and
# resolve peer ranges differently, so it must not decide the tree.
RUN npm install -g npm@latest
WORKDIR /workspace
# npm ci checks the lockfile against the root manifest, its .npmrc and every
# workspace manifest. It installs the closure of ${packageName}, whose
# devDependencies hold the Prisma CLI, so the CLI is the version of the
# lockfile. allowScripts runs @prisma/engines, which downloads the schema
# engine that migrate deploy runs.
COPY package-lock.json package.json .npmrc ./
COPY --parents **/package.json ./
RUN npm ci --workspace=${packageName} --no-audit --no-fund

WORKDIR /workspace/${projectRoot}
COPY ${projectRoot}/prisma.config.ts ${projectRoot}/schema.prisma ./
COPY ${projectRoot}/models ./models
COPY ${projectRoot}/migrations ./migrations

CMD ["npx", "prisma", "migrate", "deploy"]
`;
}

/** The lines that a backend's startup.ts gets: the client, connected before the app serves. */
export function startupClientTs(packageName: string): string {
  return `import { createPrisma } from '${packageName}';

// One query before the app serves, so a database that refuses the
// CONNECTION_STRING stops the boot. $connect() is not enough: on a driver
// adapter it opens no connection. server.ts disconnects on SIGTERM.
export const prisma = createPrisma({
  connectionString: process.env.CONNECTION_STRING,
});
await prisma.$queryRaw\`SELECT 1\`;
`;
}
