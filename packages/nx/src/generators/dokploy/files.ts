export function composeYml(stack: Stack): string {
  const { name, app, database } = stack;
  const pull = stack.registry
    ? `# The images are private GHCR packages: OpenTofu stores a Dokploy registry,
# which logs the server in to GHCR, and the compose pulls with that login.`
    : `# The images are public GHCR packages, so the server needs no registry login.
# They hold the compiled app, never a secret; those come from the environment.`;
  const postgres = database
    ? `  postgres:
    image: postgres:18-alpine
${logging}    environment:
      POSTGRES_DB: ${database.role}
      POSTGRES_USER: ${database.role}
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD}
    # Postgres 18 keeps its data in a folder of its major version under
    # /var/lib/postgresql (PGDATA=/var/lib/postgresql/18/docker), so the volume
    # holds the parent folder and a major upgrade finds the old data beside it.
    volumes:
      - pgdata:/var/lib/postgresql
    healthcheck:
      test: ['CMD-SHELL', 'pg_isready -h 127.0.0.1 -U ${database.role} -d ${database.role}']
      interval: 5s
      timeout: 5s
      retries: 10
    restart: unless-stopped

  # One-shot: applies the Prisma migrations of ${database.root} before the
  # backend starts (${database.root}/Dockerfile.migration).
  migrate:
    image: ${image(stack, 'migrate')}
    pull_policy: always
    environment:
      CONNECTION_STRING: \${CONNECTION_STRING}
    depends_on:
      postgres:
        condition: service_healthy
    restart: 'no'

`
    : '';
  const backendDatabase = database
    ? `    environment:
      CONNECTION_STRING: \${CONNECTION_STRING}
    depends_on:
      postgres:
        condition: service_healthy
      migrate:
        condition: service_completed_successfully
`
    : '';
  const networks = database
    ? `    networks:
      default: {}
      dokploy-network: {}
`
    : `    networks:
      dokploy-network: {}
`;
  const volumes = database
    ? `
volumes:
  pgdata: {}
`
    : '';
  return `# ${name} Dokploy compose template (raw), production only: the ${app.name}
# image${database ? ', Postgres and the one-shot migrate service' : ''}.
#
# OpenTofu owns this compose and its environment (infra/src/environments/
# production). Do not edit them in the Dokploy panel. Its placeholders resolve
# from that environment; write a literal dollar sign as $$.
#
${pull}

services:
${postgres}  ${app.name}:
    image: ${image(stack, app.name)}
    # A compose deploy reuses the cached image unless told to pull.
    pull_policy: always
    restart: unless-stopped
${logging}${backendDatabase}${networks}    labels:
      - 'traefik.enable=true'
      - 'traefik.docker.network=dokploy-network'
      - 'traefik.http.routers.${name}-web.rule=Host(\`\${PUBLIC_HOST}\`)'
      - 'traefik.http.routers.${name}-web.entrypoints=web'
      - 'traefik.http.routers.${name}-web.middlewares=redirect-to-https@file'
      - 'traefik.http.routers.${name}-web.service=${name}'
      - 'traefik.http.routers.${name}-websecure.rule=Host(\`\${PUBLIC_HOST}\`)'
      - 'traefik.http.routers.${name}-websecure.entrypoints=websecure'
      - 'traefik.http.routers.${name}-websecure.tls.certresolver=letsencrypt'
      - 'traefik.http.routers.${name}-websecure.service=${name}'
      - 'traefik.http.services.${name}.loadbalancer.server.port=${app.port}'

networks:
  dokploy-network:
    external: true
${volumes}`;
}

export function versionsTf(stack: Stack): string {
  const providers = providersOf(stack)
    .map(
      (provider) => `    ${provider.name} = {
      source  = "${provider.source}"
      version = "${provider.version}"
    }`,
    )
    .join('\n');
  return `terraform {
  required_version = ">= 1.12.3"

  required_providers {
${providers}
  }
}
`;
}

/** The lock blocks, in the order of their source addresses, as \`tofu init\` writes them. */
export function lockHcl(stack: Stack): string {
  const blocks = providersOf(stack)
    .map((provider) => provider.lock)
    .toSorted((a, b) => a.localeCompare(b));
  return `# This file is maintained automatically by "tofu init".
# Manual edits may be lost in future updates.

${blocks.join('\n\n')}
`;
}

