export function ciYml(stack: Stack): string {
  return `name: CI

on:
  pull_request:
    branches: [main]
  push:
    branches: [main]

# A new push to a pull request replaces its run; every commit on main keeps
# its own run.
concurrency:
  group: \${{ github.workflow }}-\${{ github.event_name == 'pull_request' && github.ref || github.sha }}
  cancel-in-progress: \${{ github.event_name == 'pull_request' }}

permissions:
  # nx-set-shas reads this workflow's runs to find the last green commit.
  actions: read
  contents: read

jobs:
  ci:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v7
        with:
          fetch-depth: 0

      - name: Set up the workspace
        uses: JanuaryLabs/zukhruf/.github/actions/setup-workspace@main

      # ${stack.projectName}:typecheck runs tofu fmt and validate.
      - name: Set up OpenTofu
        uses: opentofu/setup-opentofu@v2
        with:
          tofu_version: latest
          tofu_wrapper: false

      - name: Find what changed since the last green commit
        id: shas
        uses: nrwl/nx-set-shas@v5

      - parallel:
          - name: Check Nx workspace sync
            run: npx nx sync:check

          - name: Check formatting
            run: npx prettier --check .

      # With no green commit yet, nx-set-shas falls back to HEAD~1 and affected
      # would see only the last commit, so the first green run checks it all.
      - name: Lint, type check, test and build what changed
        env:
          NO_PREVIOUS_BUILD: \${{ steps.shas.outputs.noPreviousBuild }}
        run: |
          if [ "$NO_PREVIOUS_BUILD" = "true" ]; then
            npx nx run-many -t lint typecheck test build
          else
            npx nx affected -t lint typecheck test build
          fi
`;
}

export function deployYml(stack: Stack): string {
  const { name, app, database, registry } = stack;
  const images = [
    { image: `${name}-${app.name}`, dockerfile: `${app.root}/Dockerfile` },
    ...(database
      ? [
          {
            image: `${name}-migrate`,
            dockerfile: `${database.root}/Dockerfile.migration`,
          },
        ]
      : []),
  ];
  const buildMatrix = images
    .map(
      ({ image, dockerfile }) =>
        `          - image: ${image}\n            dockerfile: ${dockerfile}`,
    )
    .join('\n');
  const promoteMatrix = images
    .map(({ image }) => `          - image: ${image}`)
    .join('\n');
  const imageCheck = app.imageProjects
    .map((project) => `has ${project}`)
    .join(' || ');
  const tfEnv = registry
    ? `
      # The Dokploy registry logs the server in to GHCR with this token.
      TF_ENV: >-
        {"TF_VAR_ghcr_pull_token": \${{ toJSON(secrets.GHCR_PULL_TOKEN) }}}`
    : '';
  const packageAccess = registry
    ? `
    # The packages are private: when a package is not linked to this repo, its
    # settings must give this repo's Actions write access (Manage Actions
    # access), or the push is refused.`
    : '';
  return `# Ships every green commit on main, in order: the images, then the infra
# stack, then the rollout. Nothing here is run by hand: a push to main drives
# CI, and CI's success drives this.
name: Deploy

on:
  workflow_run:
    workflows: [CI]
    types: [completed]
    branches: [main]

# One rollout at a time, queued, never cancelled.
concurrency:
  group: deploy
  cancel-in-progress: false

permissions:
  # nx-set-shas reads this workflow's runs to find the last successful deploy.
  actions: read
  contents: read

env:
  SHA: \${{ github.event.workflow_run.head_sha }}

jobs:
  gate:
    if: github.event.workflow_run.conclusion == 'success' && github.event.workflow_run.event == 'push'
    runs-on: ubuntu-latest
    outputs:
      current: \${{ steps.head.outputs.current }}
      image: \${{ steps.affected.outputs.image }}
      infra: \${{ steps.affected.outputs.infra }}
    steps:
      - name: Checkout main
        uses: actions/checkout@v7
        with:
          fetch-depth: 0

      # A newer commit has its own CI run and deploy; shipping this one now
      # would roll main back.
      - name: Ship only the commit CI tested
        id: head
        run: |
          if [ "$(git rev-parse HEAD)" = "$SHA" ]; then
            echo "current=true" >> "$GITHUB_OUTPUT"
          else
            echo "main moved past $SHA; its own deploy ships the newer commit."
            echo "current=false" >> "$GITHUB_OUTPUT"
          fi

      - name: Set up the workspace
        if: steps.head.outputs.current == 'true'
        uses: JanuaryLabs/zukhruf/.github/actions/setup-workspace@main

      - name: Find the last successful deploy
        if: steps.head.outputs.current == 'true'
        id: shas
        uses: nrwl/nx-set-shas@v5
        with:
          workflow-id: deploy.yml
          last-successful-event: workflow_run

      # The images hold the projects that their Dockerfiles build.
      - name: Decide what ships
        if: steps.head.outputs.current == 'true'
        id: affected
        env:
          NO_PREVIOUS_BUILD: \${{ steps.shas.outputs.noPreviousBuild }}
        run: |
          if [ "$NO_PREVIOUS_BUILD" = "true" ]; then
            echo "No successful deploy yet: shipping everything."
            {
              echo "image=true"
              echo "infra=true"
            } >> "$GITHUB_OUTPUT"
            exit 0
          fi
          projects="$(npx nx show projects --affected --json)"
          echo "Affected since the last deploy: $projects"
          has() { printf '%s' "$projects" | jq -e --arg p "$1" 'index($p) != null' >/dev/null; }
          if ${imageCheck}; then
            echo "image=true" >> "$GITHUB_OUTPUT"
          else
            echo "image=false" >> "$GITHUB_OUTPUT"
          fi
          # The base is the last successful deploy, so an infra change whose
          # rollout failed stays affected until a rollout succeeds.
          if has ${stack.projectName}; then
            echo "infra=true" >> "$GITHUB_OUTPUT"
          else
            echo "infra=false" >> "$GITHUB_OUTPUT"
          fi

  # Each image is pushed under the commit first; promote moves :latest only
  # after every image of the commit exists.
  image:
    needs: gate
    if: needs.gate.outputs.current == 'true' && needs.gate.outputs.image == 'true'
    runs-on: ubuntu-latest${packageAccess}
    permissions:
      contents: read
      packages: write
    strategy:
      fail-fast: false
      matrix:
        include:
${buildMatrix}
    steps:
      - uses: actions/checkout@v7
        with:
          ref: \${{ env.SHA }}

      - name: Lowercase the image owner
        run: echo "OWNER_LC=\${GITHUB_REPOSITORY_OWNER,,}" >> "$GITHUB_ENV"

      - uses: docker/setup-buildx-action@v4

      - uses: docker/login-action@v4
        with:
          registry: ghcr.io
          username: \${{ github.actor }}
          password: \${{ secrets.GITHUB_TOKEN }}

      - name: Build \${{ matrix.image }}
        uses: docker/build-push-action@v7
        timeout-minutes: 25
        env:
          DOCKER_BUILD_RECORD_UPLOAD: 'false'
        with:
          context: .
          file: \${{ matrix.dockerfile }}
          platforms: linux/amd64
          push: true
          build-args: |
            BUILD_SHA=\${{ env.SHA }}
          tags: ghcr.io/\${{ env.OWNER_LC }}/\${{ matrix.image }}:\${{ env.SHA }}
          cache-from: type=registry,ref=ghcr.io/\${{ env.OWNER_LC }}/\${{ matrix.image }}:buildcache
          cache-to: type=registry,ref=ghcr.io/\${{ env.OWNER_LC }}/\${{ matrix.image }}:buildcache,mode=max,image-manifest=true,oci-mediatypes=true

  # The compose runs :latest; the immutable :sha stays for rollbacks.
  promote:
    needs: image
    runs-on: ubuntu-latest
    permissions:
      contents: read
      packages: write
    strategy:
      fail-fast: false
      matrix:
        include:
${promoteMatrix}
    steps:
      - name: Lowercase the image owner
        run: echo "OWNER_LC=\${GITHUB_REPOSITORY_OWNER,,}" >> "$GITHUB_ENV"

      - uses: docker/setup-buildx-action@v4

      - uses: docker/login-action@v4
        with:
          registry: ghcr.io
          username: \${{ github.actor }}
          password: \${{ secrets.GITHUB_TOKEN }}

      - name: Promote \${{ matrix.image }} to latest
        env:
          IMAGE: \${{ matrix.image }}
        run: |
          docker buildx imagetools create \\
            --tag "ghcr.io/\${OWNER_LC}/\${IMAGE}:latest" \\
            "ghcr.io/\${OWNER_LC}/\${IMAGE}:\${SHA}"

  # After new images, or with none: a failed build stops the stack, so a
  # compose that needs the new images never rolls out with the old ones.
  infra:
    needs: [gate, image, promote]
    if: >-
      always() && needs.gate.result == 'success' && needs.gate.outputs.current == 'true'
      && (needs.image.result == 'success' || needs.image.result == 'skipped')
      && (needs.promote.result == 'success' || needs.promote.result == 'skipped')
    permissions:
      contents: write
    uses: JanuaryLabs/zukhruf/.github/workflows/tofu-apply.yml@main
    with:
      stack: ${infraRoot}
      environment: production
      state_file: ${infraRoot}/src/terraform.tfstate
    secrets:
      TF_ENCRYPTION_PASSPHRASE: \${{ secrets.TF_ENCRYPTION_PASSPHRASE }}
      DOKPLOY_API_KEY: \${{ secrets.DOKPLOY_API_KEY }}
      HCLOUD_TOKEN: \${{ secrets.HCLOUD_TOKEN }}${tfEnv}

  # Dokploy runs a stored compose only on compose.deploy, so a rollout follows
  # new images, an apply that changed the stack, and any infra change since the
  # last successful deploy (a retry of a failed rollout).
  release:
    needs: [gate, promote, infra]
    if: >-
      always() && needs.infra.result == 'success'
      && (needs.promote.result == 'success' || needs.infra.outputs.changed == 'true' || needs.gate.outputs.infra == 'true')
    runs-on: ubuntu-latest
    steps:
      # Queues the rollout through the Dokploy API and waits until Dokploy
      # reports the deployment done.
      - name: Roll out the compose
        uses: JanuaryLabs/zukhruf/.github/actions/dokploy-deploy@main
        with:
          api-url: \${{ fromJSON(needs.infra.outputs.outputs).dokploy_api }}
          api-key: \${{ secrets.DOKPLOY_API_KEY }}
          compose-id: \${{ fromJSON(needs.infra.outputs.outputs).compose_id }}

      # A new image must report this commit. A rollout without one restarts the
      # old image, which reports the commit it was built from.
      - name: Wait until the ${app.name} answers
        uses: JanuaryLabs/zukhruf/.github/actions/wait-for-health@main
        with:
          url: https://\${{ fromJSON(needs.infra.outputs.outputs).host }}/api/healthz
          sha: \${{ needs.promote.result == 'success' && env.SHA || '' }}
`;
}
