/** The root of the OpenTofu project. */
export const infraRoot = 'infra';

function providersOf(stack: Stack): Provider[] {
  return [
    dokployProvider,
    hcloudProvider,
    ...(stack.database ? [randomProvider] : []),
  ];
}

