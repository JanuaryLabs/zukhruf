import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { readFontMetrics } from '../font-metrics-from-files.ts';

const require = createRequire(import.meta.url);
const target = new URL(
  '../../lib/layouts/text/font-metrics.generated.ts',
  import.meta.url,
);

const sources = ['@fontsource/geist-sans', '@fontsource/geist-mono'].map(
  (name) => {
    const manifest: unknown = JSON.parse(
      readFileSync(require.resolve(`${name}/package.json`), 'utf8'),
    );
    const version =
      typeof manifest === 'object' && manifest && 'version' in manifest
        ? String(manifest.version)
        : 'unknown';
    return `${name}@${version}`;
  },
);

writeFileSync(
  target,
  `// Generated by \`nx run diagram:generate-font-metrics\` from the latin woff2
// files of ${sources.join(' and ')}. Do not edit.
import type { FontFace, FontWeight } from './font.ts';

/**
 * One face and weight, in font units. Ascent, descent and line gap come from
 * hhea, which the generator checks equals OS/2 typo with USE_TYPO_METRICS set.
 * \`advances\` and \`kerning\` map a value to the characters (or ASCII pairs) that
 * have it.
 */
export type FaceMetrics = {
  unitsPerEm: number;
  ascent: number;
  descent: number;
  lineGap: number;
  advances: Record<string, string>;
  kerning: Record<string, string>;
};

export type FontMetricsTable = Record<FontFace, Record<FontWeight, FaceMetrics>>;

export const FONT_METRICS: FontMetricsTable = ${asciiJson(readFontMetrics())};
`,
);
console.log(`Wrote ${target.pathname}`);

/** Combining marks and invisible spaces stay legible as `\uXXXX` escapes. */
function asciiJson(value: unknown): string {
  return JSON.stringify(value).replaceAll(
    /[^\x20-\x7e]/g,
    (character) =>
      `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
}
